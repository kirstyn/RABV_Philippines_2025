# Function that uses Kelly for ≤22, otherwise viridis
make_palette <- function(levels_vec) {
  levels_vec <- unique(levels_vec)
  n <- length(levels_vec)
  if (n <= 22) {
    cols <- pals::kelly(n + 2)[-c(1,2)]
  } else {
    cols <- viridisLite::viridis(n)
  }
  cols <- cols[1:n]
  names(cols) <- levels_vec
  cols
}


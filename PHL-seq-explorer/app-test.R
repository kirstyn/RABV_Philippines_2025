# -----------------------------
# Server
# -----------------------------
server <- function(input, output, session) {
  
  # Reactive filtered data
  filtered_data <- reactive({
    df <- full_data
    if (input$host_common != "All") df <- df %>% filter(Host_common == input$host_common)
    if (input$region != "All") df <- df %>% filter(Region_short == input$region)
    df <- df %>%
      filter(year(Preferred_date) >= input$year_range[1],
             year(Preferred_date) <= input$year_range[2])
    df
  })
  
  # ---- Overview Tab ----
  output$total_seq <- renderText({ nrow(full_data) })
  output$study_seq <- renderText({ sum(full_data$Source %in% c("speedier", "phd"), na.rm = TRUE) })
  output$public_seq <- renderText({ sum(!full_data$Source %in% c("speedier", "phd"), na.rm = TRUE) })
  
  output$host_table <- renderTable({
    filtered_data() %>%
      tabyl(Host_common) %>%
      adorn_pct_formatting(digits = 1) %>%
      mutate(n = as.integer(n))
  })
  
  output$host_plot <- renderPlotly({
    df <- filtered_data()
    p <- ggplot(df, aes(x = Host_common, fill = Host_common)) +
      geom_bar() +
      theme_minimal() +
      labs(title = "Sequences by Host", x = "Host", y = "Count") +
      scale_fill_brewer(palette = "Set2") +
      theme(legend.position = "none")
    ggplotly(p)
  })
  
  output$temporal_region_plot <- renderPlotly({
    df <- filtered_data() %>%
      filter(!is.na(Preferred_date) & !is.na(Region_short)) %>%
      mutate(Year = year(Preferred_date)) %>%
      group_by(Year, Region_short) %>%
      summarise(n = n(), .groups = "drop") %>%
      arrange(Year)
    df$Region_short <- factor(df$Region_short, levels = region_levels)
    p <- ggplot(df, aes(x = factor(Year), y = n, fill = Region_short)) +
      geom_col() +
      scale_fill_manual(values = region_cols) +
      theme_minimal() +
      labs(title = "Sequences per Year by Region", x = "Year", y = "Count", fill = "Region") +
      theme(axis.text.x = element_text(angle = 45, hjust = 1))
    ggplotly(p) %>% layout(legend = list(orientation = "v", x = 1.05))
  })
  
  # -----------------------------
  # Region & Province barplots
  # -----------------------------
  output$region_plot <- renderPlotly({
    df_region <- filtered_data() %>%
      filter(!is.na(Region_short)) %>%
      group_by(Region_short) %>%
      summarise(n = n(), .groups = "drop") %>%
      arrange(n)
    df_region$Region_short <- factor(df_region$Region_short, levels = df_region$Region_short)
    p <- ggplot(df_region, aes(x = Region_short, y = n, fill = Region_short)) +
      geom_col() +
      scale_fill_manual(values = region_cols) +
      coord_flip() +
      theme_minimal(base_size = 14) +
      labs(title = "By Region", x = "Region", y = "Number of sequences", fill = "Region") +
      theme(legend.position = "none")
    ggplotly(p)
  })
  
  output$province_plot <- renderPlotly({
    df_stacked <- filtered_data() %>%
      filter(!is.na(Province_std) & !is.na(Region_short)) %>%
      group_by(Province_std, Region_short) %>%
      summarise(n = n(), .groups = "drop")
    
    province_totals <- df_stacked %>%
      group_by(Province_std) %>%
      summarise(total = sum(n), .groups = "drop") %>%
      arrange(total)
    
    df_stacked$Province_std <- factor(df_stacked$Province_std, levels = province_totals$Province_std)
    df_stacked$Region_short <- factor(df_stacked$Region_short, levels = region_levels)
    
    p <- ggplot(df_stacked, aes(x = Province_std, y = n, fill = Region_short)) +
      geom_col() +
      scale_fill_manual(values = region_cols) +
      coord_flip() +
      theme_minimal(base_size = 14) +
      labs(title = "By Province (coloured by Region)", x = "Province", y = "Number of sequences", fill = "Region") +
      theme(legend.position = "top")
    ggplotly(p)
  })
  
  # -----------------------------
  # Leaflet maps
  # -----------------------------
  output$map_points_leaflet <- renderLeaflet({
    pts <- full_data %>% filter(!is.na(Longitude) & !is.na(Latitude))
    pal_points <- colorFactor(palette = region_cols, domain = region_levels)
    leaflet(pts) %>%
      addProviderTiles(providers$CartoDB.Positron) %>%
      setView(lng = 121, lat = 12, zoom = 5) %>%
      addCircleMarkers(lng = ~Longitude, lat = ~Latitude,
                       color = ~pal_points(Region_short),
                       radius = 3, fillOpacity = 0.7,
                       label = ~paste0(Sample_ID, " (", Host_type, ")")) %>%
      addLegend("bottomright", pal = pal_points, values = pts$Region_short, title = "Region")
  })
  
  # -----------------------------
  # Phylogenetic tree (interactive)
  # -----------------------------
  output$timetree_plotly <- renderPlotly({
    p <- plot_timetree_interactive(filtered_data(), region_cols) +
      geom_tiplab(aes(label = seq_name, key = seq_name))  # remove text
    
    ggplotly(p, source = "timetree_plotly") %>%
      layout(dragmode = "select") %>%
      event_register("plotly_selected") %>%
      event_register("plotly_relayout")
  })
  # -----------------------------
  # Map update when tree tips are selected
  # -----------------------------
  observe({
    sel <- event_data("plotly_selected", source = "timetree_plotly")
    pts <- filtered_data() %>% filter(!is.na(Longitude) & !is.na(Latitude))
    
    if (!is.null(sel)) {
      selected_ids <- sel$key
      pts <- pts %>% filter(Sample_ID %in% selected_ids)
    }
    
    pal_points <- colorFactor(palette = region_cols, domain = region_levels)
    
    leafletProxy("map_points_leaflet", data = pts) %>%
      clearMarkers() %>%
      addCircleMarkers(
        lng = ~Longitude, lat = ~Latitude,
        color = ~pal_points(Region_short),
        radius = 3, fillOpacity = 0.7,
        label = ~paste0(Sample_ID, " (", Host_type, ")")
      ) %>%
      clearControls() %>%
      addLegend("bottomright", pal = pal_points, values = pts$Region_short, title = "Region")
  })
  
  # -----------------------------
  # Downloads
  # -----------------------------
  output$download_csv <- downloadHandler(
    filename = function() paste0("filtered_metadata_", Sys.Date(), ".csv"),
    content = function(file) write.csv(filtered_data(), file, row.names = FALSE)
  )
  
  output$download_ids <- downloadHandler(
    filename = function() paste0("sequence_ids_", Sys.Date(), ".txt"),
    content = function(file) writeLines(filtered_data()$Sample_ID, con = file)
  )
  
  output$download_fasta <- downloadHandler(
    filename = function() paste0("filtered_sequences_", Sys.Date(), ".fasta"),
    content = function(file) {
      selected_seqs <- fasta_seqs[names(fasta_seqs) %in% filtered_data()$Sample_ID]
      writeXStringSet(selected_seqs, filepath = file)
    }
  )
  
}

# -----------------------------
# Run App
# -----------------------------
shinyApp(ui = ui, server = server)
full_data <- read.csv("../processed_data/processed_metadata/gathered_metadata/final/PHL_metadata_matchedToSeq_2025-11-03_n794.csv", stringsAsFactors = FALSE)
full_data$Preferred_date <- lubridate::dmy(full_data$Preferred_date)

# Load simplified shapefiles 
phl_prov_simp <- readRDS("../processed_data/gis_data/phl_prov_simp.rds")
phl_region_simp <- readRDS("../processed_data/gis_data/phl_region_simp.rds")

# Load all sequences
all_seqs_fasta <- "../processed_data/processed_sequences/241025_PHL_all_n794.fasta"
fasta_seqs <- readDNAStringSet(all_seqs_fasta)

# Source your tree plotting script (make sure it has geom_tiplab with label & key = seq_name)
source("../scripts/R/plot-timetree-interactive.R")  

# -----------------------------
# Mapping of full region names to abbreviations
# -----------------------------
region_lookup <- phl_region_simp %>%
  st_drop_geometry() %>%
  distinct(ADM1_EN) %>%
  mutate(
    Region_short = str_extract(ADM1_EN, "\\((.*?)\\)") %>% str_remove_all("[()]"),
    Region_short = ifelse(is.na(Region_short),
                          case_when(
                            ADM1_EN == "Mimaropa Region" ~ "Mimaropa",
                            TRUE ~ gsub(" Region", "", ADM1_EN)
                          ),
                          Region_short)
  )

full_data <- full_data %>%
  left_join(region_lookup, by = c("Region_std" = "ADM1_EN")) %>%
  mutate(Region_short = ifelse(is.na(Region_short), Region_std, Region_short))

region_levels <- sort(unique(full_data$Region_short))
n <- length(region_levels)
region_cols <- kelly(n + 2)[-c(1,2)]
names(region_cols) <- region_levels

